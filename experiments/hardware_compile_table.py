"""Transpiled circuit cost per gate set × topology — the table `reports/hardware-plan.md` cites.

Was a pytest side effect (review 002 finding 6); a test that mutates the tree is not a test, and
the artefact had no seed, no git hash and no backend.  The numbers depend on the parameter vector
(``_synth_1q`` drops rotations that are ``0 mod 2π``, so ``np.zeros`` gives a much shorter
circuit than a random draw), so the seed has to travel with them.

Sizes are the paper's: Flappy Bird is ``Network(2, 4)`` = 7 qubits ``[PTQNN Fig 10]``, the
bit-count task is ``Network(5, 5)`` = 11 qubits ``[PTQNN Fig 5]``.

    uv run python experiments/hardware_compile_table.py

writes ``experiments/runs/hardware-compile-table/<stamp>/{table.md,meta.json}`` and refreshes
``reports/hardware-compile-table.md`` from it.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np

from ptqnn.circuits import neurons
from ptqnn.hardware import gatesets as gs
from ptqnn.hardware import transpile as tp
from ptqnn.noise.presets import DeviceSpec

ROOT = Path(__file__).resolve().parents[1]
TOPOLOGIES = ("linear", "heavy-hex", "all-to-all")


def git_hash() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            cwd=ROOT,
        )
        head = out.stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain"], capture_output=True, text=True, cwd=ROOT
        ).stdout.strip()
        return f"{head}-dirty" if dirty else head
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def fixture_device(gset: gs.GateSet, topology: str) -> DeviceSpec:
    """A DeviceSpec carrying only what ``compile_for`` reads: no invented calibration."""
    return DeviceSpec(
        name=f"{gset.name}_{topology}",
        vendor="fixture",
        technology="gate-set × topology fixture",
        n_qubits=27,
        topology=topology,
        native_1q=gset.one_qubit,
        native_2q=gset.two_qubit,
        t1_us=None,
        t2_us=None,
        gate_1q_error=0.0,
        gate_1q_ns=0.0,
        gate_2q_error=0.0,
        gate_2q_ns=0.0,
        readout_p01=0.0,
        readout_p10=0.0,
        readout_ns=0.0,
    )


def compile_table(seed: int = 17) -> tuple[list[str], dict[str, Any]]:
    """Build the markdown table and the machine-readable rows it was rendered from."""
    rng = np.random.default_rng(seed)
    nets = {
        "flappy Network(2,4), 7q": neurons.Network(2, 4),
        "bit-count Network(5,5), 11q": neurons.Network(5, 5),
    }
    lines = [
        "# Transpiled circuit cost: gate set × topology",
        "",
        "Generated by `experiments/hardware_compile_table.py`; the run dir next to it carries",
        "the seed and git hash.  Do not edit by hand.",
        "",
        "`depth` is the ASAP layer count of the *native* circuit; `n_2q` counts every native",
        "entangler in it, including the three each routed SWAP costs; `n_swap` is the number of",
        "SWAPs the router inserted (each CRX costs 2 entanglers, each SWAP 3, so",
        "`n_2q = 2·n_CRX + 3·n_swap`).  Routing is greedy nearest-neighbour and **not optimal**",
        "— see `ptqnn.hardware.transpile.route`.  The prototype network is complete-bipartite",
        "(every input couples to every hidden qubit), the worst possible fit for a lattice,",
        "which is why the trapped-ion all-to-all rows cost no SWAPs at all.",
        "",
    ]
    rows: dict[str, list[dict[str, Any]]] = {}
    for label, net in nets.items():
        circ = net.circuit(net.random_params(rng))
        base = tp.metrics(circ)
        lines += [
            f"## {label}",
            "",
            f"Logical circuit: depth {base['depth']}, {base['n_2q']} CRX, {base['n_1q']} 1q gates.",
            "",
            "| gate set | topology | depth | n_1q | n_2q | n_swap |",
            "|---|---|---:|---:|---:|---:|",
        ]
        rows[label] = []
        for gset in (gs.GATESETS[k] for k in sorted(gs.GATESETS)):
            for topo in TOPOLOGIES:
                m = tp.compile_for(circ, fixture_device(gset, topo)).metrics
                rows[label].append({"gateset": gset.name, "topology": topo, **m})
                lines.append(
                    f"| {gset.name} | {topo} | {m['depth']} | {m['n_1q']} | "
                    f"{m['n_2q']} | {m['n_swap']} |"
                )
        lines.append("")
    return lines, {
        "n_crx": {k: tp.metrics(v.circuit(np.zeros(v.n_params)))["n_2q"] for k, v in nets.items()},
        "rows": rows,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seed", type=int, default=17)
    ap.add_argument("--out", type=Path, default=ROOT / "reports" / "hardware-compile-table.md")
    args = ap.parse_args()

    lines, data = compile_table(args.seed)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    run = ROOT / "experiments" / "runs" / "hardware-compile-table" / stamp
    run.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    (run / "table.md").write_text(text, encoding="utf-8")
    (run / "meta.json").write_text(
        json.dumps(
            {
                "script": "experiments/hardware_compile_table.py",
                "seed": args.seed,
                "git_hash": git_hash(),
                "backend": "none (transpiler only; no simulation)",
                "timestamp": stamp,
                "topologies": list(TOPOLOGIES),
                "gatesets": sorted(gs.GATESETS),
                "data": data,
            },
            indent=2,
            default=str,
        )
        + "\n",
        encoding="utf-8",
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(text)
    print(f"run dir: {run}")


if __name__ == "__main__":
    main()
